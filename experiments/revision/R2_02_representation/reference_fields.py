"""Historical and learned-predicted congestion sources for the controlled R2-02 experiment."""
from __future__ import annotations
import json
from pathlib import Path
import numpy as np
from scipy import ndimage
import torch
from learned_prediction import LearnedOccupancyPredictor, predict_dense


class DenseTimeLookup:
    """Dictionary-like read-only view over [time,y,x] dense data."""
    def __init__(self, array):
        a = np.asarray(array, dtype=np.float32)
        if a.ndim != 3:
            raise ValueError("Dense field must be [time,y,x]")
        self.array = a

    def get(self, key, default=0.0):
        x, y, t = key
        t = int(t)
        x = int(x)
        y = int(y)
        if 0 <= t < self.array.shape[0] and 0 <= y < self.array.shape[1] and 0 <= x < self.array.shape[2]:
            return float(self.array[t, y, x])
        return default


def gaussian_kernel_3d(config):
    ts = np.arange(-config.T, config.T + 1, dtype=np.float64)
    ys = np.arange(-config.L, config.L + 1, dtype=np.float64)
    xs = np.arange(-config.L, config.L + 1, dtype=np.float64)
    tt, yy, xx = np.meshgrid(ts, ys, xs, indexing="ij")
    k = np.exp(-(xx*xx + yy*yy)/(2*config.sigma_l**2) - (tt*tt)/(2*config.sigma_t**2))
    k /= k.sum()
    return k


def gaussian_smooth_dense(raw, config):
    """Exactly the same finite, normalized zero-padded kernel semantics as CPS-A's updater."""
    raw = np.asarray(raw, dtype=np.float32)
    return ndimage.convolve(raw, gaussian_kernel_3d(config), mode="constant", cval=0.0).astype(np.float32)


def _meta_path(root, map_name, load):
    return Path(root) / f"historical_{map_name}_{load}.json"


def historical_path(root, map_name, load):
    return Path(root) / f"historical_{map_name}_{load}.npz"


def learned_path(root, map_name):
    return Path(root) / f"learned_{map_name}.pt"


def require_historical(root, map_name, load, config):
    p = historical_path(root, map_name, load)
    m = _meta_path(root, map_name, load)
    if not p.exists() or not m.exists():
        raise FileNotFoundError(
            f"Missing historical artifact for Map {map_name}, load {load}. "
            f"Run prepare_reference_artifacts.py first. Expected {p}"
        )
    meta = json.loads(m.read_text(encoding="utf-8"))
    if meta.get("generator") != "collision_only_controlled_planner":
        raise ValueError("Historical artifact was not generated by the predeclared neutral calibration protocol")
    arr = np.load(p, allow_pickle=False)["raw_expected_occupancy"]
    if arr.shape[0] < config.reference_horizon + 1:
        raise ValueError("Historical artifact horizon is shorter than Config.reference_horizon")
    return arr[:config.reference_horizon+1], meta


def require_learned(root, map_name, grid, tasks, config):
    p = learned_path(root, map_name)
    if not p.exists():
        raise FileNotFoundError(
            f"Missing learned predictor for Map {map_name}. Run prepare_reference_artifacts.py first. Expected {p}"
        )
    bundle = torch.load(p, map_location="cpu", weights_only=False)
    meta = bundle["metadata"]
    if meta.get("label_generator") != "collision_only_controlled_planner":
        raise ValueError("Learned labels were not generated by the predeclared neutral calibration protocol")
    if (int(meta["height"]), int(meta["width"])) != (grid.height, grid.width):
        raise ValueError("Learned predictor dimensions do not match the selected map")
    model = LearnedOccupancyPredictor(grid.height, grid.width, hidden=int(meta.get("hidden", 24)))
    model.load_state_dict(bundle["state_dict"])
    free = (grid.grid == 0).astype(np.float32)
    raw = predict_dense(model, tasks, free, config.reference_horizon, device="cpu")
    return raw, meta
